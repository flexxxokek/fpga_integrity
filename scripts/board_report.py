#!/usr/bin/env python3
"""Render the DE2-115 Quartus compile results into docs/results/board.md.

Fmax comes from TimeQuest (`.sta.rpt`), utilisation from the Fitter report
(`.fit.rpt`).  No simulated clock is ever reported as Fmax.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

TARGET_MHZ = 12.5  # CLOCK_50 / 4 fabric divider


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def first(pattern: str, text: str) -> str | None:
    match = re.search(pattern, text, re.IGNORECASE)
    return match.group(1) if match else None


def number(pattern: str, text: str) -> int | None:
    value = first(pattern, text)
    if value is None:
        return None
    digits = re.sub(r"[^0-9]", "", value)
    return int(digits) if digits else None


def fmax_mhz(text: str) -> float | None:
    # Prefer the Fmax summary row (two MHz columns) for the stand clock;
    # the clock list also mentions 12.5 MHz as the requested frequency.
    match = re.search(
        r";\s*([\d.]+)\s*MHz\s*;\s*[\d.]+\s*MHz\s*;\s*CLK_12M5", text)
    if match:
        return float(match.group(1))
    for pattern in (
        r";\s*Fmax\s*=\s*([\d.]+)\s*MHz",
        r"Fmax\s*[:=]\s*([\d.]+)\s*MHz",
        r"\|\s*Fmax\s*\|\s*([\d.]+)\s*MHz",
        r";\s*([\d.]+)\s*MHz\s*;\s*[\d.]+\s*MHz\s*;\s*CLOCK",
        r"Maximum frequency[^\n]*?([\d.]+)\s*MHz",
    ):
        value = first(pattern, text)
        if value:
            return float(value)
    return None


def slack_ns(text: str) -> float | None:
    for pattern in (
        r"Worst-case setup slack is\s*(-?[\d.]+)",
        r"Worst-case slack\s*[:=]\s*(-?[\d.]+)",
        r"\|\s*Slack\s*\|\s*(-?[\d.]+)",
        r"Worst Negative Slack[^\n]*?(-?\d+\.\d+)",
    ):
        value = first(pattern, text)
        if value:
            return float(value)
    return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", default="boards/de2_115")
    parser.add_argument("--out", default="docs/results/board.md")
    args = parser.parse_args(argv)

    project = Path(args.project)
    # Quartus 21.1 writes reports into the project directory; newer versions
    # use output_files/.  Support both.
    reports = sorted(set(project.glob("*.rpt")) |
                     set((project / "output_files").glob("*.rpt")))
    fit_files = [p for p in reports if p.name.endswith(".fit.rpt")]
    sta_files = [p for p in reports if p.name.endswith(".sta.rpt")]
    if not fit_files or not sta_files:
        print("no Quartus .fit.rpt / .sta.rpt found; run `make board-build` first",
              file=sys.stderr)
        return 1

    fit = read_text(fit_files[0])
    sta = "".join(read_text(path) for path in sta_files)

    le = number(r"Total logic elements\s*[:;]\s*([\d,]+)", fit)
    regs = number(r"Total registers\s*[:;]\s*([\d,]+)", fit)
    mem = number(r"Total block memory bits\s*[:;]\s*([\d,]+)", fit)
    dsp = number(r"Total DSP Blocks\s*[:;]\s*([\d,]+)", fit)
    fmax = fmax_mhz(sta)
    wns = slack_ns(sta)

    def fmt(value: int | float | None, suffix: str = "") -> str:
        return f"{value:,}{suffix}" if value is not None else "—"

    timing = "—"
    if fmax is not None:
        timing = "met" if fmax >= TARGET_MHZ else "not met"
    if wns is not None:
        timing += f" (worst slack {wns:+.3f} ns)"

    lines = [
        "# DE2-115 board results",
        "",
        "Generated by `make board-build` from the Quartus Fitter and TimeQuest",
        "reports. Fmax below is a **vendor static-timing result**, not a",
        "simulation clock or a gate-equivalent proxy.",
        "",
        "| Metric | Value |",
        "|---|---:|",
        "| Device | EP4CE115F29C7 (Cyclone IV E, speed grade 7) |",
        f"| Target clock | {TARGET_MHZ:.3f} MHz (80.000 ns) = CLOCK_50 / 4 |",
        f"| Fmax (TimeQuest) | {fmt(fmax, ' MHz')} |",
        f"| Timing closure | {timing} |",
        f"| Logic elements (ALMs/LEs) | {fmt(le)} / 114,480 |",
        f"| Registers | {fmt(regs)} |",
        f"| Block memory bits | {fmt(mem)} / 3,981,312 |",
        f"| DSP blocks | {fmt(dsp)} / 266 |",
        "",
        "Raw reports: `boards/de2_115/*.rpt`.",
        "",
        "The compiled stand includes all six lanes (SHA-256 enabled), the UART",
        "report formatter and a 12.5 MHz stand clock derived from the 50 MHz",
        "input.  HEX7 shows the selected lane (KEY[1]), HEX6..4 = live packet",
        "count, HEX3..0 = live byte count; LEDG[5:0] marks per-lane pass and",
        "LEDG[8] = done.",
        "",
    ]

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}: Fmax={fmt(fmax, ' MHz')}, timing={timing}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
