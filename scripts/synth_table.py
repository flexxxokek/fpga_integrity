#!/usr/bin/env python3
"""Render the synthesis CSV as a comparison table for the documentation."""

from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", default="data/synthesis.csv")
    parser.add_argument("--out", default="docs/results/synthesis.md")
    args = parser.parse_args(argv)

    rows: dict[tuple[str, str], dict[str, str]] = {}
    with open(args.input, newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            rows[(row["algo"], row["width"])] = row

    algos = sorted({algo for algo, _ in rows})
    widths = sorted({int(width) for _, width in rows})
    lines = [
        "# Static hardware cost (Yosys synthesis)",
        "",
        "Generated by `make synth` from `data/synthesis.csv`. **Gate-equivalent",
        "cells** are generic Yosys gates from `synth -noabc` (LUT proxy), and",
        "`FF` is the number of sequential cells. Fmax is left blank in this",
        "Yosys-only table: reporting a simulated clock",
        "as Fmax would be misleading. Vendor Fmax/LE counts are in board.md.",
        "The same flow is applied to every core, so the",
        "columns are directly comparable with each other.",
        "",
        "| algorithm | " + " | ".join(
            f"gates w{w} | FF w{w}" for w in widths
        ) + " |",
        "|---|" + "|".join("---:|---:" for _ in widths) + "|",
    ]
    for algo in algos:
        cells = []
        for width in widths:
            row = rows.get((algo, str(width)))
            cells.append(row["luts"] if row and row["luts"] else "-")
            cells.append(row["ffs"] if row and row["ffs"] else "-")
        lines.append(f"| {algo} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "Full per-configuration logs: `syn/reports/` (regenerated by `make synth`). Raw data:",
        "`data/synthesis.csv`. Synthesis scripts: `syn/yosys/build/`.",
        "",
    ]
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
